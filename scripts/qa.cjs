const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { app, dialog, clipboard, ClipboardItem } = require('electron');
const { readClipboardFiles, copyFiles } = require('../app/workflow.cjs');
const { createHash } = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const pause = ms => new Promise(r => setTimeout(r, ms));
exports.run = async ({ win, importFiles, saveItems, files, queueQuick }) => {
  const out = path.join(root, 'test-output'); await fs.mkdir(out, { recursive: true });
  const js = async code => { try { return await win.webContents.executeJavaScript(code); } catch(e) { console.error('QA step failed:',code); throw e; } };
  const screenshot = async name => { await pause(180); await fs.writeFile(path.join(out, name), (await win.webContents.capturePage()).toPNG()); };
  const errors = [];
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  await pause(500);
  assert.equal(await js('languageReady'), true);
  await js("changeLanguage('en')");
  assert.equal(await js("document.documentElement.lang"), 'en');
  assert.equal(await js("$('start').textContent.trim()"), 'Compress');
  const untranslated = await js(`(()=>{const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT),result=[];while(w.nextNode()){const n=w.currentNode;if(n.parentElement.closest('script,style,select'))continue;const value=n.nodeValue.trim();if(/[가-힣]/.test(value)&&!value.includes('압축깡패'))result.push(value)}return result})()`);
  assert.deepEqual(untranslated, [], 'All static English text is translated');
  await screenshot('15-english-idle.png');
  await js("changeLanguage('ko')");
  assert.equal(await js("$('start').textContent.trim()"), '압축 시작');
  await js("localStorage.removeItem('press-gang-settings'); $('target').value=1; $('unit').value=1000000; previousUnit=1000000; settingsChanged();");
  await screenshot('01-idle.png');
  const sample = path.join(root, 'samples/무거운-휴가사진.png');
  const hash = createHash('sha256').update(await fs.readFile(sample)).digest('hex');
  const response = await importFiles([sample]);
  assert.equal(response.imported.length, 1);
  await js(`accept(${JSON.stringify(response)}); document.getElementById('target').value='0.3'; document.getElementById('unit').value='1000000'; settingsChanged();`);
  await screenshot('02-imported.png');
  await js(`document.getElementById('start').click();`);
  await pause(250);
  await screenshot('03-working.png');
  const until = Date.now() + 60000;
  while (await js('busy') && Date.now() < until) await pause(200);
  assert.equal(await js('busy'), false);
  const item = [...files.values()][0];
  assert.ok(item.result, 'result returned over IPC'); assert.ok(item.result.reached); assert.ok(item.result.bytes <= 300000);
  const stateBeforeLanguage = await js('JSON.stringify({selected,ids:[...items.keys()],bytes:items.get(selected).result.bytes,config:configNow()})');
  await js("changeLanguage('en')");
  assert.equal(await js('JSON.stringify({selected,ids:[...items.keys()],bytes:items.get(selected).result.bytes,config:configNow()})'), stateBeforeLanguage, 'Language switch preserves the queue, selection, settings and result');
  assert.equal(await js("$('copy-selected').querySelector('span').textContent"), 'Copy file');
  assert.equal(await js("errorText('복사된 이미지가 없습니다. 사진 파일이나 스크린샷을 복사한 뒤 붙여넣어주세요.')"), 'No image on the clipboard. Copy an image file or screenshot, then paste.');
  await screenshot('16-english-result.png');
  win.setContentSize(980,681); await pause(150);
  await screenshot('17-english-compact.png');
  assert.ok(await js("document.documentElement.scrollWidth <= innerWidth && $('copy-selected').getBoundingClientRect().bottom < innerHeight && $('quality-note').getBoundingClientRect().bottom < innerHeight"));
  win.setContentSize(1264,842);
  const englishPicker = dialog.showOpenDialog;
  try {
    let dialogOptions;
    dialog.showOpenDialog = async (_win, options) => { dialogOptions = options; return {canceled:true,filePaths:[]}; };
    await js('api.pick()'); assert.equal(dialogOptions.title, 'Add files'); assert.equal(dialogOptions.filters[0].name, 'Images');
    await js('api.save([selected])'); assert.equal(dialogOptions.title, 'Choose a folder for the results');
  } finally { dialog.showOpenDialog = englishPicker; }
  await js("$('about-button').click()"); await screenshot('18-english-help.png');
  await js("$('about-dialog').close(); $('workflow-button').click()"); await pause(150); await screenshot('19-english-workflow.png');
  await js("$('workflow-dialog').close(); changeLanguage('ko')");
  await pause(500); await screenshot('04-result.png');
  assert.equal(await js("$('inline-comparison').dataset.view"), 'split');
  await js("$('inline-slider').value=27; updateInlineSlider();");
  assert.equal(await js("$('inline-line').style.left"), '27%');
  await js("$('inline-slider').value=50; updateInlineSlider();");
  await js("document.querySelector('button[data-view=after]').click();");
  assert.equal(await js("$('inline-comparison').dataset.view"), 'after');
  await js("document.querySelector('button[data-view=split]').click();");
  await js("$('target').value=0; settingsChanged();");
  assert.equal(await js("$('start').disabled"), true);
  assert.equal(await js("$('target-error').hidden"), false);
  await js("document.querySelector('[data-bytes=\"500000\"]').click();");
  assert.equal(await js("configNow().targetBytes"), 500000);
  assert.equal(await js("$('settings-changed').hidden"), false);
  await screenshot('07-settings-changed.png');
  await js("$('target').value=0.3; $('unit').value=1000000; previousUnit=1000000; settingsChanged();");
  assert.equal(await js("$('settings-changed').hidden"), true);
  await js("$('unit').value=1000; $('unit').dispatchEvent(new Event('change'));");
  assert.equal(await js("configNow().targetBytes"), 300000);
  await js("$('unit').value=1000000; $('unit').dispatchEvent(new Event('change'));");
  await js(`document.getElementById('compare').click();`);
  await screenshot('05-compare.png');
  const saved = await saveItems([item.id], out); assert.ok(saved[0].path);
  const m = await sharp(saved[0].path).metadata(); assert.equal(m.width, item.result.width);
  assert.equal(createHash('sha256').update(await fs.readFile(sample)).digest('hex'), hash);
  await js(`document.getElementById('compare-dialog').close(); document.getElementById('about-button').click();`);
  await screenshot('06-about.png');
  await js(`document.getElementById('about-dialog').close();`);
  const layout = await js(`({ scroll:document.documentElement.scrollWidth, width:innerWidth, bottom:document.querySelector('footer').getBoundingClientRect().bottom, height:innerHeight, api:!!window.gang, node:typeof require })`);
  assert.ok(layout.scroll <= layout.width); assert.ok(layout.bottom <= layout.height); assert.equal(layout.node, 'undefined');
  win.setContentSize(980, 681);
  await pause(200);
  await screenshot('08-compact.png');
  const compact = await js("({width:innerWidth,scroll:document.documentElement.scrollWidth,start:$('start').getBoundingClientRect().bottom,save:$('save-selected').getBoundingClientRect().bottom,height:innerHeight,note:$('quality-note').getBoundingClientRect().bottom})");
  assert.ok(compact.scroll <= compact.width);
  assert.ok(compact.save < compact.height);
  assert.ok(compact.note < compact.height);
  win.setContentSize(1264, 841);
  const tiny = path.join(out, '투명한-작은-아이콘.png');
  await sharp({create:{width:128,height:128,channels:4,background:{r:232,g:90,b:45,alpha:0.5}}}).png().toFile(tiny);
  const second = await importFiles([tiny]);
  await js(`accept(${JSON.stringify(second)}); $('start').click();`);
  const batchUntil = Date.now() + 60000;
  while (await js('busy') && Date.now() < batchUntil) await pause(100);
  assert.equal(await js('busy'), false);
  assert.equal(await js('readyItems().length'), 2);
  assert.equal(await js("$('save-all').hidden"), false);
  assert.equal(await js("items.get(selected).result.unchanged"), true);
  await screenshot('09-batch.png');
  // The result layer must not double-composite transparent pixels over the original.
  const pixel = await js("(()=>{const r=$('inline-comparison').getBoundingClientRect();return {left:Math.round(r.x+r.width/2+40),top:Math.round(r.y+r.height/2+40),width:1,height:1}})()");
  await js("setView('before')"); await pause(180);
  const beforePixel = await sharp((await win.webContents.capturePage()).toPNG()).extract(pixel).raw().toBuffer();
  await js("setView('after')"); await pause(180);
  const afterPixel = await sharp((await win.webContents.capturePage()).toPNG()).extract(pixel).raw().toBuffer();
  assert.deepEqual(beforePixel, afterPixel, 'unchanged alpha image has identical before/after preview');
  await js("setView('split')");
  const originalPicker = dialog.showOpenDialog;
  try {
    dialog.showOpenDialog = async () => ({ canceled:false, filePaths:[out] });
    await js("save([selected])");
    assert.equal(await js("!!items.get(selected).savedPath"), true);
    assert.equal(await js("$('reveal-saved').hidden"), false);
    assert.equal(await js("saving"), false);
    await screenshot('10-saved.png');
  } finally { dialog.showOpenDialog = originalPicker; }
  await js("document.querySelector('.file-row.selected .remove').click();");
  await pause(150);
  assert.equal(await js('items.size'), 1);
  assert.equal(await js("$('save-all').hidden"), true);
  // Preserve the user's clipboard in memory; never log or persist its contents.
  const snapshot = [];
  for (const entry of await clipboard.read()) {
    const data = {}; for (const type of entry.types) data[type] = await entry.getType(type);
    snapshot.push(new ClipboardItem(data));
  }
  try {
    await js('copyResults([selected])');
    const copied = await readClipboardFiles(); assert.equal(copied.length,1);
    assert.deepEqual(await fs.readFile(copied[0]), await fs.readFile(item.output), 'file clipboard preserves exact compressed bytes');
    assert.equal(await js('items.get(selected).copied'), true);
    await screenshot('11-copy.png');
    const firstCopied = copied[0];
    await js('copyResults([selected])');
    assert.equal((await readClipboardFiles())[0], firstCopied, 'repeat copy does not litter duplicate files');
    await js('pasteFiles(false)');
    assert.equal(await js('items.size'),2,'Explorer file clipboard imports');
    await clipboard.write([new ClipboardItem({'image/png':new Blob([await fs.readFile(tiny)],{type:'image/png'})})]);
    await js('pasteFiles(true)');
    assert.equal(await js('items.size'),3);
    assert.equal(await js('items.get(selected).result.unchanged'),true,'screenshot paste and compress');
    const originalOutput = item.output;
    await js("$('target').value=0.5; settingsChanged(); compressIds([selected]);");
    assert.equal(item.output,originalOutput,'selected recompression does not touch other results');
    await js('copyResults(readyItems().map(i=>i.id))');
    assert.equal((await readClipboardFiles()).length,2,'copy all excludes uncompressed file');
    const beforeEmpty = await js('items.size');
    await clipboard.writeText('not an image');
    assert.match(await js('pasteFiles().then(()=>"unexpected success",e=>e.message)'), /이미지가 없습니다/);
    assert.equal(await js('items.size'),beforeEmpty);
    // A launch received during compression waits; it then compresses and saves only the new file.
    await js("$('start').click()");
    queueQuick(['--quick','500000','--image',sample]);
    const quickUntil=Date.now()+60000;
    while (Date.now()<quickUntil && !(await js('items.size===4 && !busy && !quickHandling && !!items.get(selected)?.savedPath'))) await pause(100);
    assert.equal(await js('items.size'),4);
    assert.equal(await js('items.get(selected).target'),500000);
    assert.ok(await js('!!items.get(selected).savedPath'),'queued quick launch saves result');
    assert.equal(await js('items.get(selected).result.reached'),true);
    await screenshot('12-quick-result.png');
    win.setContentSize(980,681); await pause(120);
    const batchLayout=await js("({copy:$('copy-selected').getBoundingClientRect().bottom,reveal:$('reveal-saved').getBoundingClientRect().bottom,height:innerHeight,scroll:document.documentElement.scrollWidth,width:innerWidth})");
    assert.ok(batchLayout.copy<batchLayout.height); assert.ok(batchLayout.reveal<batchLayout.height); assert.ok(batchLayout.scroll<=batchLayout.width);
    await screenshot('13-batch-compact.png');
    win.setContentSize(1264,842);
    await js("$('workflow-button').click()"); await pause(300); await screenshot('14-workflow.png');
    await js("$('workflow-dialog').close(); $('clear-queue').click()");
    const clearUntil=Date.now()+5000; while(await js('items.size') && Date.now()<clearUntil) await pause(50);
    assert.equal(await js('items.size'),0);
    assert.ok((await fs.stat(firstCopied)).isFile(),'clearing queue preserves copied files');
  } finally { if(snapshot.length) await clipboard.write(snapshot); else clipboard.clear(); }
  assert.equal(errors.length, 0, errors.join('\n'));
  const report = { passed: true, sourceBytes: item.bytes, result: { bytes: item.result.bytes, width: item.result.width, height: item.result.height, reached: item.result.reached }, originalUnchanged: true, contextIsolation: true, inlineComparison: true, transparentPreviewPixelMatch: true, saveFeedback: true, presetAndUnitConversion: true, settingsChangeNotice: true, batchAndRemoval: true, layout, compact, saved: saved[0].name, checkedAt: new Date().toISOString() };
  Object.assign(report,{clipboardFileBytes:true,clipboardImage:true,clipboardRestored:true,copyAll:true,selectedRecompression:true,queuedQuickLaunch:true,clearPreservesSavedFiles:true,englishStaticText:true,languageSwitchPreservesWork:true,englishNativeDialogs:true,englishCompactLayout:true});
  await fs.writeFile(path.join(out, 'native-qa.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  win.close();
};
